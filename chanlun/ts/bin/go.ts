// 缠论's contract in Go (../../SPEC.md; ../../go/): the records' types, ../go/chanlun/records.go, made from the Zod
// schemas of ../src, or, with --check, compared with the file, or with the file of a module named:
//   bun bin/go.ts [--check [DIR]]
// The rules and the JSON are the Go form's own, written by hand beside it. The K-lines, and a price's Decimal, are
// market's Go form's (../../../market/go/market): named here, made there. A fault to stderr, exit 1.
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { klineSchema, massiveKlineSchema } from "@qi/market";
import { z } from "zod";
import {
  consolidationSchema,
  fractalSchema,
  lineSchema,
  massiveRunSchema,
  mergedBarSchema,
  moveSchema,
  runSchema,
  segmentSchema,
} from "../src/index.ts";
import { golang, type Schema } from "./golang.ts";

const home = join(import.meta.dirname, "..", "..", "go");
const file = join("chanlun", "records.go");
const records = z
  .registry<{ id: string }>()
  .add(klineSchema, { id: "KLine" })
  .add(massiveKlineSchema, { id: "MassiveKLine" })
  .add(mergedBarSchema, { id: "MergedBar" })
  .add(fractalSchema, { id: "Fractal" })
  .add(lineSchema, { id: "Line" })
  .add(segmentSchema, { id: "Segment" })
  .add(moveSchema, { id: "Move" })
  .add(consolidationSchema, { id: "Consolidation" })
  .add(runSchema, { id: "Run" })
  .add(massiveRunSchema, { id: "MassiveRun" });
// market's types: its K-lines, and its Decimal for a price
const market = "github.com/zhifengzhang-sz/qi-v2-contracts/market/go/market";
const uses = {
  types: { KLine: "market.KLine", MassiveKLine: "market.MassiveKLine", Decimal: "market.Decimal" },
  imports: [market],
};
// each record's line, after its name (SPEC.md, The records and The run)
const docs = {
  MergedBar: "包含's merged bar; ConfirmEnd not set while it is still merging (SPEC.md, Merged bar).",
  Fractal: "分型, at the merged bar MIndex (SPEC.md, Fractal).",
  Line: "a line, and 笔 (Stroke); ConfirmEnd not set while it is still going on (SPEC.md, Line).",
  Segment: "线段 of level Level: a line's fields, and its level (SPEC.md, Line).",
  Move: "走势 of level Level: a line's fields, and its level (SPEC.md, Line).",
  Consolidation:
    "中枢 of level Level; ConfirmEnd not set while it is under construction (SPEC.md, Consolidation).",
  Run: "a run of the base's K-lines: its seven parts, Segments, Moves and Consolidations by level (SPEC.md, The run).",
  MassiveRun: "a run whose K-lines are Massive's, under the same rules (SPEC.md, The run).",
};
const fail = (error: string): never => {
  process.stderr.write(`go: ${error}\n`);
  return process.exit(1);
};
const { version } = (await readFile(join(import.meta.dirname, "..", "package.json"), "utf8")
  .then((t) => JSON.parse(t) as unknown)
  .catch(() => fail("cannot read package.json"))) as { readonly version: string };
const header = [
  "Code generated by ts/bin/go.ts from the Zod schemas of ts/src; DO NOT EDIT.",
  "",
  `缠论's contract, chanlun ${version} (SPEC.md): the records' types, their fields and types, made from the Zod`,
  "schemas; not edited by hand. The rules and the JSON are written by hand beside them (rules.go, json.go, codec.go).",
];

// Zod's JSON Schema, of which the mapping reads its part (Schema)
const schemas = z.toJSONSchema(records, { unrepresentable: "throw" }).schemas as {
  readonly [name: string]: Schema;
};
const made = golang(
  schemas,
  docs,
  "chanlun",
  header,
  [["Version", "the contract's version (SPEC.md), of which these types are.", version]],
  uses,
);
if (!made.ok) fail(made.error);
else if (process.argv[2] === "--check") {
  const out = join(resolve(process.argv[3] ?? home), file);
  const now = await readFile(out, "utf8").catch(() => "");
  if (now !== made.text) fail(`${out} is not what the schemas make: bun bin/go.ts`);
  process.stdout.write(`go: ${out} is what the schemas make\n`);
} else {
  await writeFile(join(home, file), made.text);
  process.stdout.write(`go: ${join(home, file)} written\n`);
}
