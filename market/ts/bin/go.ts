// The market data contract in Go (../../SPEC.md; ../../go/): the records' types, ../go/market/records.go, made from the
// Zod schemas of ../src, or, with --check, compared with the file, or with the file of a module named:
//   bun bin/go.ts [--check [DIR]]
// The rules and the JSON are the Go form's own, written by hand beside it. A fault to stderr, exit 1.
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { z } from "zod";
import {
  klineSchema,
  massiveKlineSchema,
  massiveOngoingKlineSchema,
  ongoingKlineSchema,
} from "../src/index.ts";
import { golang, type Schema } from "./golang.ts";

const home = join(import.meta.dirname, "..", "..", "go");
const file = join("market", "records.go");
const records = z
  .registry<{ id: string }>()
  .add(klineSchema, { id: "KLine" })
  .add(massiveKlineSchema, { id: "MassiveKLine" })
  .add(ongoingKlineSchema, { id: "OngoingKLine" })
  .add(massiveOngoingKlineSchema, { id: "MassiveOngoingKLine" });
// each record's line, after its name (SPEC.md, The records)
const docs = {
  KLine: "a K-line, the base contract, a complete bar (SPEC.md, K-line). Its rule: KLine.Check.",
  MassiveKLine:
    "Massive's K-line: the base's fields, and vw and n of Massive's row (SPEC.md, Massive's K-line).",
  OngoingKLine:
    "the ongoing K-line of the base, a bar still going on, in no run (SPEC.md, The ongoing K-line).",
  MassiveOngoingKLine: "Massive's ongoing K-line (SPEC.md, The ongoing K-line).",
};
const fail = (error: string): never => {
  process.stderr.write(`go: ${error}\n`);
  return process.exit(1);
};
const { version } = (await readFile(join(import.meta.dirname, "..", "package.json"), "utf8")
  .then((t) => JSON.parse(t) as unknown)
  .catch(() => fail("cannot read package.json"))) as { readonly version: string };
const header = [
  "Code generated by ts/bin/go.ts from the Zod schemas of ts/src; DO NOT EDIT.",
  "",
  `The market data contract, market ${version} (SPEC.md): the records' types, their fields and types, made from the`,
  "Zod schemas; not edited by hand. The rules and the JSON are written by hand beside them (rules.go, json.go,",
  "codec.go).",
];

// Zod's JSON Schema, of which the mapping reads its part (Schema)
const schemas = z.toJSONSchema(records, { unrepresentable: "throw" }).schemas as {
  readonly [name: string]: Schema;
};
const made = golang(schemas, docs, "market", header, [
  ["Version", "the contract's version (SPEC.md), of which these types are.", version],
]);
if (!made.ok) fail(made.error);
else if (process.argv[2] === "--check") {
  const out = join(resolve(process.argv[3] ?? home), file);
  const now = await readFile(out, "utf8").catch(() => "");
  if (now !== made.text) fail(`${out} is not what the schemas make: bun bin/go.ts`);
  process.stdout.write(`go: ${out} is what the schemas make\n`);
} else {
  await writeFile(join(home, file), made.text);
  process.stdout.write(`go: ${join(home, file)} written\n`);
}
